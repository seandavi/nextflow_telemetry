"""Convert the pinned cMD data dictionary CSV into a LinkML schema (cmd.yaml).

Deterministic: same CSV in, same YAML out. The generated file is committed; edit the
pin (`just cmd-schema-pin <commit>`), never the YAML. Dynamic enums become
`reachable_from` and are not validated here (needs a pinned ontology, #341).

    uv run python scripts/cmd_schema.py            # regenerate cmd.yaml
"""
from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

import yaml

SCHEMA_DIR = Path(__file__).resolve().parent.parent / "src" / "nextflow_telemetry" / "meta" / "schema"
CSV_PATH = SCHEMA_DIR / "cMD_data_dictionary.csv"
YAML_PATH = SCHEMA_DIR / "cmd.yaml"

RANGES = {"character": "string", "double": "float", "numeric": "float", "integer": "integer"}
# Unknown prefixes are an error: add the expansion here when upstream starts using one.
PREFIXES = {
    "FMA": "http://purl.obolibrary.org/obo/FMA_",
    "HANCESTRO": "http://purl.obolibrary.org/obo/HANCESTRO_",
    "MONDO": "http://purl.obolibrary.org/obo/MONDO_",
    "MRO": "http://purl.obolibrary.org/obo/MRO_",
    "NCBITaxon": "http://purl.obolibrary.org/obo/NCBITaxon_",
    "NCIT": "http://purl.obolibrary.org/obo/NCIT_",
    "SNOMED": "http://snomed.info/id/",
    "UBERON": "http://purl.obolibrary.org/obo/UBERON_",
}


def _na(v: str) -> str | None:
    return None if v in ("", "NA") else v


def _enum_name(col: str) -> str:
    return "".join(p.capitalize() for p in col.split("_")) + "Enum"


def _curies(v: str | None) -> list[str]:
    out = re.split(r"[|;]", v) if v else []
    for c in out:
        if c.split(":", 1)[0] not in PREFIXES:
            raise ValueError(f"unknown CURIE prefix in {c!r}")
    return out


def _enum(r: dict[str, str]) -> dict | None:
    col, kind = r["col.name"], r["corpus.type"]
    av = _na(r["allowedvalues"])
    labels = av.split("|") if av else []
    static = _curies(_na(r["static.enum"]))
    roots = _curies(_na(r["dynamic.enum"]))
    if kind in ("binary", "custom_enum", "static_enum"):
        if static and len(static) != len(labels):
            raise ValueError(f"{col}: {len(labels)} labels vs {len(static)} static.enum IDs")
        pvs = {lab: ({"meaning": static[i]} if static else {}) for i, lab in enumerate(labels)}
        return {"permissible_values": pvs}
    if "dynamic_enum" in kind and roots:
        prop = r["dynamic.enum.property"]
        if prop not in ("children", "descendant", "NA"):
            raise ValueError(f"{col}: unexpected dynamic.enum.property {prop!r}")
        reach: dict = {"source_nodes": roots, "relationship_types": ["rdfs:subClassOf"]}
        if prop != "NA":  # NA upstream: leave is_direct unset rather than guess (#341)
            reach["is_direct"] = prop == "children"
        if static:
            # ponytail: upstream gives the static IDs without labels; the CURIE is the text.
            return {"permissible_values": {c: {"meaning": c} for c in static},
                    "include": [{"reachable_from": reach}]}
        return {"reachable_from": reach}
    return None


def convert(rows: list[dict[str, str]]) -> dict:
    slots: dict[str, dict] = {}
    enums: dict[str, dict] = {}
    for r in rows:
        col = r["col.name"]
        if r["col.class"] not in RANGES:
            raise ValueError(f"{col}: unknown col.class {r['col.class']!r}")
        slot: dict = {"description": r["description"], "range": RANGES[r["col.class"]]}
        if r["unique"] == "unique":
            slot["identifier"] = True
        if r["required"] == "required":
            slot["required"] = True
        if r["multiplevalues"] == "TRUE":
            slot["multivalued"] = True
        enum = _enum(r)
        pattern = _na(r["allowedvalues"])
        if enum is not None:
            enums[_enum_name(col)] = {"description": f"Allowed values for {col}.", **enum}
            slot["range"] = _enum_name(col)
        elif pattern and slot["range"] == "string":
            slot["pattern"] = pattern
        ann = {"corpus_type": r["corpus.type"], "display_order": int(r["display.order"]),
               "display_group": r["display.group"]}
        if _na(r["delimiter"]):
            ann["delimiter"] = r["delimiter"]
        if enum is None and pattern and slot["range"] != "string":
            ann["allowed_pattern"] = pattern
        slot["annotations"] = ann
        slots[col] = slot
    return {
        "id": "https://github.com/waldronlab/curatedMetagenomicDataCuration/cmd",
        "name": "cmd",
        "title": "curatedMetagenomicData sample metadata",
        "description": "Generated by scripts/cmd_schema.py from cMD_data_dictionary.csv; see pin.json. Do not edit.",
        "prefixes": {"linkml": "https://w3id.org/linkml/", "cmdschema": "https://github.com/waldronlab/curatedMetagenomicDataCuration/cmd/",
                     "rdfs": "http://www.w3.org/2000/01/rdf-schema#", **PREFIXES},
        "default_prefix": "cmdschema",
        "default_range": "string",
        "imports": ["linkml:types"],
        "classes": {"Sample": {"description": "One curated cMD sample row.", "tree_root": True,
                               "slots": list(slots)}},
        "slots": slots,
        "enums": enums,
    }


def render(csv_path: Path = CSV_PATH) -> str:
    with csv_path.open(newline="", encoding="utf-8") as f:
        schema = convert(list(csv.DictReader(f)))
    return yaml.safe_dump(schema, sort_keys=False, allow_unicode=True, width=10_000)


def check_pin(csv_path: Path = CSV_PATH) -> None:
    import hashlib
    pin = json.loads((csv_path.parent / "pin.json").read_text())
    got = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    if got != pin["sha256"]:
        raise SystemExit(f"{csv_path.name} sha256 {got} != pin.json {pin['sha256']}")


if __name__ == "__main__":
    check_pin()
    YAML_PATH.write_text(render(), encoding="utf-8")
    print(f"wrote {YAML_PATH}", file=sys.stderr)
